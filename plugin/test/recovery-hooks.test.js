test('sandbox: an egress proxy is handed to the container only when the network is on', () => {
  const off = sandboxCommand('/repo', 'npm test', { proxy: 'http://egress:3128' });
  assert.equal(off.network, 'none');
  assert.equal(off.proxy, null);
  assert.ok(!off.argv.some((arg) => /HTTPS_PROXY/.test(arg)));

  const on = sandboxCommand('/repo', 'npm test', { registries: ['registry.npmjs.org'], proxy: 'http://egress:3128' });
  assert.equal(on.network, 'bridge');
  assert.equal(on.proxy, 'http://egress:3128');
  assert.ok(on.argv.includes('HTTPS_PROXY=http://egress:3128'));
  assert.ok(on.argv.includes('NO_PROXY=localhost,127.0.0.1'));
  assert.match(on.caveat, /proxy's allow-list is the rule/);

  const bare = sandboxCommand('/repo', 'npm test', { registries: ['registry.npmjs.org'], proxy: null });
  assert.match(bare.caveat, /VIBEKIT_EGRESS_PROXY/);
});

