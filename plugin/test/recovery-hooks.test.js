test('init --from-speckit writes the folder: principles become rules, EARS criteria are carried, the rest are asks', async () => {
  const root = tempDir('vibekit-speckit-');
  await mkdir(join(root, 'memory'), { recursive: true });
  await mkdir(join(root, 'specs/001-cancel'), { recursive: true });
  await writeFile(join(root, 'memory/constitution.md'), '# Constitution\n\n## Principles\n\n- Tests before code\n- No secrets in the repo\n');
  await writeFile(join(root, 'specs/001-cancel/spec.md'), [
    '# Feature: Cancel a booking',
    'Members cancel confirmed bookings and get refunds.',
    '',
    '## Acceptance Criteria',
    '- When a member cancels a confirmed booking, the system shall issue a refund.',
    '- It should feel fast.',
    '',
  ].join('\n'));
  const read = await readSpecKit(root);
  const result = await convertSpecKit(root, read, { folder: 'vibekit' });

  assert.equal(result.rules, 2);
  assert.equal(result.requirements.length, 1);
  assert.equal(result.requirements[0].carried, 1);
  assert.equal(result.requirements[0].skipped, 1);
  const rules = await readFile(join(root, 'vibekit/standards/rules.md'), 'utf8');
  assert.match(rules, /From the Spec Kit constitution/);
  assert.match(rules, /- Tests before code/);
  const requirement = await readFile(join(root, `vibekit/product/requirements/${result.requirements[0].id}.md`), 'utf8');
  assert.match(requirement, /^confidence: low$/m);
  assert.match(requirement, /AC-1  When a member cancels a confirmed booking/);
  assert.ok(!/feel fast/.test(requirement), 'a criterion that is not EARS is not carried as one');
  assert.match(requirement, /converted from specs\/001-cancel\/spec\.md/);
});

// ------------------------------------------------------------------ tracker/<user> merge-back

test('a tracker decision is committed on tracker/<user> with trailers and merged back when clean', async () => {
  const root = await repo();
  await mkdir(join(root, 'vibekit/workflow/asks'), { recursive: true });
  await writeFile(join(root, 'vibekit/workflow/asks/A-001.md'), 'status: open\n');
  git(root, 'add', '-A');
  git(root, 'commit', '-qm', 'folder');

  const before = await snapshot(root, 'vibekit');
  await new Promise((wait) => setTimeout(wait, 20));
  await writeFile(join(root, 'vibekit/workflow/asks/A-001.md'), 'status: answered\n');
  const paths = changedBetween(before, await snapshot(root, 'vibekit'));
  assert.deepEqual(paths, ['vibekit/workflow/asks/A-001.md']);

  const landed = await commitToTracker(root, {
    user: 'j.naidoo@example.com', name: 'J. Naidoo', paths,
    message: 'ask.answer A-001: answered', trailers: ['VibeKit-Role: human', 'VibeKit-Via: tracker'],
  });
  assert.equal(landed.committed, true);
  assert.equal(landed.branch, 'tracker/j.naidoo');
  assert.equal(landed.merged, true);
  assert.equal(landed.into, 'main');
  assert.equal(landed.pushed, false);

  const shown = git(root, 'show', '-s', '--format=%an <%ae>%n%B', landed.commit);
  assert.match(shown, /^J\. Naidoo <j\.naidoo@example\.com>/);
  assert.match(shown, /VibeKit-Via: tracker/);
  // a fast-forward: main is now the tracker commit, and the working tree is clean for that path
  assert.equal(git(root, 'rev-parse', 'main'), landed.commit);
  assert.equal(git(root, 'status', '--porcelain', '--', 'vibekit/'), '');
  assert.equal(trackerBranch('Some One@corp.example'), 'tracker/some-one');
});

test('a tracker commit that would not merge cleanly stays on its branch, and the page is told', async () => {
  const root = await repo();
  await mkdir(join(root, 'vibekit/workflow'), { recursive: true });
  await writeFile(join(root, 'vibekit/workflow/plan.md'), 'line one\n');
  git(root, 'add', '-A');
  git(root, 'commit', '-qm', 'folder');

  // the tracker branch records one change to the plan…
  await writeFile(join(root, 'vibekit/workflow/plan.md'), 'line one — from the phone\n');
  const first = await commitToTracker(root, { user: 'a@example.com', paths: ['vibekit/workflow/plan.md'], message: 'first' });
  assert.equal(first.merged, true);

  // …then main moves on the same line by hand, and a second tracker change lands on the old base.
  await writeFile(join(root, 'vibekit/workflow/plan.md'), 'line one — from the terminal\n');
  git(root, 'commit', '-qam', 'terminal edit');
  git(root, 'update-ref', 'refs/heads/tracker/a', first.commit); // the branch never saw the terminal edit
  await writeFile(join(root, 'vibekit/workflow/plan.md'), 'line one — from the phone again\n');
  const second = await commitToTracker(root, { user: 'a@example.com', paths: ['vibekit/workflow/plan.md'], message: 'second' });
  assert.equal(second.committed, true);
  assert.equal(second.merged, false);
  assert.equal(second.left, 'tracker/a');
  assert.match(second.why, /pull request/);
  assert.notEqual(git(root, 'rev-parse', 'main'), second.commit);
  assert.equal(git(root, 'rev-parse', 'tracker/a'), second.commit);
});

