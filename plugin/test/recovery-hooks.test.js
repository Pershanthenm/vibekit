test('a human approval below <!-- local --> in a generated folder file survives regeneration', async () => {
  const root = tempDir('vibekit-local-');
  const config = { name: 'p', description: null, architecture: 'layered', stack: {}, commands: {}, entities: [] };
  await generateFolder(root, config, { folder: 'vibekit' });
  const path = join(root, 'vibekit/product/design/tokens.md');
  const first = await readFile(path, 'utf8');
  assert.match(first, /^<!-- generated by vibekit/);
  await writeFile(path, `${first.trimEnd()}\n\n<!-- local -->\napproved: 2026-09-24 by You\n`);

  await generateFolder(root, config, { folder: 'vibekit' });
  const second = await readFile(path, 'utf8');
  assert.match(second, /^<!-- generated by vibekit/, 'still generated, still ours');
  assert.match(second, /<!-- local -->\napproved: 2026-09-24 by You/, 'the approval is still there');
  const { approvalOf } = await import('../src/folder/workflow.js');
  assert.equal(approvalOf(second)?.by, 'You');
});
