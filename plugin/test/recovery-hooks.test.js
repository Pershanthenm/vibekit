test('a queued action whose target moved is refused with a 409 the page may re-confirm', async () => {
  const root = tempDir('vibekit-queue-');
  await generateFolder(root, { name: 'q', description: null, architecture: 'layered', stack: {}, commands: {}, entities: [] }, { folder: 'vibekit' });
  const { createRequirement } = await import('../src/folder/requirements.js');
  await createRequirement(root, { id: 'REQ-001', title: 'x', kind: 'requirement', size: 'S', source: null }, 'vibekit');

  await assert.rejects(
    apply(root, null, { action: 'req.status', id: 'REQ-001', status: 'ready', expect: { status: 'in-progress' } }),
    (error) => error instanceof Changed && /now "draft", not "in-progress"/.test(error.message),
  );
  // the same request without an expectation is a live one and meets the ordinary gates instead
  await assert.rejects(
    apply(root, null, { action: 'req.status', id: 'REQ-001', status: 'ready' }),
    (error) => !(error instanceof Changed),
  );
});

