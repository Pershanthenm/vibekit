// ------------------------------------------------------------------ recovery fixture helpers

test('the recovery fixture reads its next step from the checkpoint alone and compares evidence without the volatile parts', () => {
  assert.equal(stepFromCheckpoint('## Checkpoint\ndone: x\nnext: write src/cancel.js for AC-1\n'), 2);
  assert.equal(stepFromCheckpoint('next: commit on req/REQ-001 and run vibekit verify'), 4);
  assert.equal(stepFromCheckpoint('next: set REQ-001 tested'), 5);
  assert.equal(stepFromCheckpoint('next: something else'), null);

  const a = normaliseEvidence('## Evidence\n\ncommit abc1234 · 2026-09-24T10:00:00Z\n\n- build `node -e ok`  exit 0  1s\n- test `node --test`  exit 0  12s\n\n## Log\n');
  const b = normaliseEvidence('## Evidence\n\ncommit def5678 · 2026-09-25T10:00:00Z\n\n- build `node -e ok`  exit 0  0s\n- test `node --test`  exit 0  9s\n');
  assert.equal(a, b);
  assert.notEqual(a, normaliseEvidence('## Evidence\n\n- build `node -e ok`  exit 1  0s\n'));

  const one = seeded(42);
  const two = seeded(42);
  assert.equal(one(), two());
  assert.ok(one() >= 0 && one() < 1);
});

