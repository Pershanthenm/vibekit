test('an external dependency added between two tags is reported as a call that is now made', async () => {
  const root = await project();
  gitInit(root);
  sh(root, 'git', 'tag', 'v0.1.0');

  // Externals are read from `## Dependencies` in the architecture record — the same place a
  // person writes them, so the diff follows the decision rather than a separate list.
  const architecture = join(root, 'vibekit/workflow/architecture.md');
  const before = await readFile(architecture, 'utf8');
  await writeFile(architecture, before.replace(/^## Dependencies$/m, '## Dependencies\n\n- Stripe · card payments'));
  sh(root, 'git', 'add', '-A');
  sh(root, 'git', 'commit', '-qm', 'feat: take payments');
  sh(root, 'git', 'tag', 'v0.2.0');

  const { markdown } = await diffDocs(root, 'v0.1.0', 'v0.2.0');
  assert.match(markdown, /Architecture changes · v0\.1\.0 → v0\.2\.0/);
  assert.match(markdown, /now calls \*\*Stripe\*\*/);
});

test('a document handed to somebody can be reproduced from its tag, byte for byte', async () => {
  // §8 acceptance 4, and the one the spec singles out as most likely to fail. Being able to
  // regenerate last quarter's document exactly is the difference between a document and a
  // claim about a document.
  //
  // The tag is taken before the document is written, because the stamp names the commit the
  // *code* came from: no file can contain the hash of the commit that carries it.
  const root = await project();
  gitInit(root);
  sh(root, 'git', 'tag', 'v1.0.0');
  await run(['arch-docs', 'hld', '--dir', root]);
  const asShipped = await readFile(join(root, 'docs/hld.md'), 'utf8');

  // The code moves on, which is the whole point: the tag must not follow it.
  await writeFile(join(root, 'vibekit/workflow/architecture.md'), '# Architecture\n\n## Dependencies\n\n- Stripe · card payments\n');
  sh(root, 'git', 'add', '-A');
  sh(root, 'git', 'commit', '-qm', 'feat: payments');
  await run(['arch-docs', 'hld', '--dir', root]);
  assert.match(await readFile(join(root, 'docs/hld.md'), 'utf8'), /Stripe/, 'today\u2019s document follows today\u2019s code');

  await run(['arch-docs', 'hld', '--dir', root, '--at', 'v1.0.0']);
  assert.equal(await readFile(join(root, 'docs/hld@v1.0.0.md'), 'utf8'), asShipped);
});

