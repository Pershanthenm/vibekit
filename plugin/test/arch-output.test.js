test('when a converter is there, the document is converted and the tool that did it is named', async () => {
  const { delimiter } = await import('node:path');
  const { mkdtemp: makeTemp, readFile: read } = await import('node:fs/promises');
  const { installFakeBin } = await import('./helpers.js');
  const bin = await makeTemp(join(tmpdir(), 'fake-pandoc-'));
  // A stand-in for pandoc: takes `<input> -o <output>`, which is the contract convert() relies on.
  await installFakeBin(bin, 'pandoc', `#!/usr/bin/env node
const fs = require('fs');
const args = process.argv.slice(2);
fs.writeFileSync(args[args.indexOf('-o') + 1], 'DOCX ' + fs.readFileSync(args[0], 'utf8').length);
`);

  const root = await project();
  await generateDocs(root, { commit: 'abc' });
  const saved = process.env.PATH;
  process.env.PATH = [bin, saved].join(delimiter);
  try {
    assert.equal(converterFor('docx')?.command, 'pandoc');
    const outcome = convert(join(root, 'docs/hld.md'), join(root, 'docs/hld.docx'), 'docx');
    assert.equal(outcome.ok, true);
    assert.equal(outcome.by, 'pandoc', 'which tool produced a document is part of being able to reproduce it');
    assert.match(await read(join(root, 'docs/hld.docx'), 'utf8'), /^DOCX \d+$/);
  } finally {
    process.env.PATH = saved;
  }
});

