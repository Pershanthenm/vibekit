/**
 * The half of the Documentation Feature Spec that leaves the repository: the document library
 * (§4), a brand read off a website (§5), history and diffs (§7), and the output formats (§4).
 *
 * These are the parts where being wrong is expensive and quiet — a logo taken from the wrong
 * site, a PDF missing its diagrams, a diff that omits a classification change a reviewer was
 * looking for. Each test below is one of those failures.
 */

const CONFIG = {
  name: 'bookings',
  description: 'A booking system for gyms.',
  architecture: 'clean',
  stack: { language: '.NET 10', web: 'Vue 3', database: 'PostgreSQL 17' },
  commands: { build: 'dotnet build', test: 'dotnet test' },
  entities: [
    { name: 'Booking', class: 'internal', fields: [{ name: 'id', type: 'uuid' }] },
    { name: 'Member', class: 'personal', fields: [{ name: 'email', type: 'string', class: 'personal' }] },
  ],
};

async function project(config = CONFIG) {
  const root = await mkdtemp(join(tmpdir(), 'vibekit-out-'));
  await generateFolder(root, config);
  await writeFile(join(root, 'vibekit/product/access.md'), '# Access\n\n| Role \\ Entity | Booking |\n| --- | --- |\n| member | CRU own |\n');
  return root;
}

// ------------------------------------------------------------ the document library (§4)

test('every document in the library renders, and each one says it is generated', async () => {
  const root = await project();
  const { documents } = await generateDocs(root, { commit: 'abc1234' });

  assert.deepEqual(documents, ['hld.md', 'lld.md', 'api-reference.md', 'data-model.md', 'runbook.md', 'srs.md', 'tech-spec.md']);
  for (const name of documents) {
    const body = await readFile(join(root, 'docs', name), 'utf8');
    assert.match(body, /^<!-- generated by vibekit/, `${name} must declare itself, or somebody edits it and loses the edit`);
  }
});

