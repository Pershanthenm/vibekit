// ------------------------------------------------------------ output formats (§4)

test('the HTML carries its diagrams inside it, so it opens offline in five years', async () => {
  const root = await project();
  await generateDocs(root, { commit: 'abc' });
  const markdown = await readFile(join(root, 'docs/hld.md'), 'utf8');

  const images = await inlineImages(markdown, join(root, 'docs'));
  assert.ok(images.size > 0, 'the HLD references diagrams; none were found to inline');

  const html = await toHtml(markdown, { docsRoot: join(root, 'docs'), brand: DEFAULT_BRAND, title: 'HLD' });
  assert.match(html, /<svg/, 'the diagrams are inlined, not linked');
  assert.doesNotMatch(html, /<img\s/, 'a linked image is a broken image on somebody else’s machine');
  assert.doesNotMatch(html, /src="https?:/);
});

test('the Markdown a document actually contains survives the trip to HTML', () => {
  const html = markdownToHtml([
    '# Title',
    '',
    'A paragraph with **bold** and `code`.',
    '',
    '| Method | Path |',
    '| --- | --- |',
    '| GET | /api |',
    '',
    '- one',
    '- two',
    '',
    '```',
    'raw <not> markup',
    '```',
  ].join('\n'));

  assert.match(html, /<h1>Title<\/h1>/);
  assert.match(html, /<strong>bold<\/strong>/);
  assert.match(html, /<code>code<\/code>/);
  assert.match(html, /<th>Method<\/th>/);
  assert.match(html, /<td>\/api<\/td>/);
  assert.match(html, /<li>one<\/li>/);
  assert.match(html, /&lt;not&gt;/, 'content is escaped, never rendered as markup it did not ask for');
});

test('a missing converter is reported with what to install, and nothing half-written is left behind', async () => {
  const { existsSync } = await import('node:fs');
  const output = join(tmpdir(), `vibekit-nonexistent-${Date.now()}.docx`);
  const saved = process.env.PATH;
  process.env.PATH = '';
  try {
    assert.equal(converterFor('docx'), null);
    const outcome = convert('/nowhere/input.html', output, 'docx');
    assert.equal(outcome.ok, false);
    assert.match(outcome.reason, /pandoc/, 'telling somebody it failed without telling them what to install wastes their afternoon');
    assert.equal(existsSync(output), false, 'a docx without its diagrams would be worse than none');
  } finally {
    process.env.PATH = saved;
  }
});

// ------------------------------------------------------------ brand extraction (§5)

test('a colour the team named beats a colour that merely appears often', () => {
  const css = ':root { --brand: #1a4d7a; --accent: #E8A317; } .x { color: #cccccc } .y { color: #cccccc } .z { color: #cccccc }';
  const colours = coloursFrom(css);
  assert.equal(colours.brand, '#1A4D7A', 'naming --brand is the team telling you which colour is the brand');
  assert.equal(colours.accent, '#E8A317');
});

test('with nothing named, the most prominent colour is used and black and white are ignored', () => {
  const colours = coloursFrom('a{color:#fff}b{color:#123456}c{color:#123456}d{color:#abc}');
  assert.equal(colours.brand, '#123456');
  assert.ok(!colours.ranked.includes('#FFFFFF'));
});

test('typefaces are read in the order the page declares them', () => {
  const type = typefacesFrom('body { font-family: "Inter", sans-serif } code { font-family: Menlo, monospace }');
  assert.equal(type.heading, 'Inter, sans-serif');
  assert.match(type.mono, /Menlo/);
});

test('the logo is found in the order the spec prefers, and always as an absolute address', () => {
  const link = logoFrom('<link rel="icon" href="/favicon.svg">', 'https://example.test/about');
  assert.equal(link.url, 'https://example.test/favicon.svg');

  const og = logoFrom('<meta property="og:image" content="img/card.png">', 'https://example.test/a/b');
  assert.equal(og.url, 'https://example.test/a/img/card.png');

  const image = logoFrom('<img src="/i/wordmark.svg" alt="Acme logo">', 'https://example.test/');
  assert.match(image.from, /logo or wordmark/);
  assert.equal(logoFrom('<img src="/i/hero.jpg" alt="a gym">', 'https://example.test/'), null);
});

test('robots.txt is honoured, including a rule that only applies to another agent', () => {
  assert.equal(disallows('User-agent: *\nDisallow: /private', '/private/page'), true);
  assert.equal(disallows('User-agent: *\nDisallow: /private', '/about'), false);
  assert.equal(disallows('User-agent: googlebot\nDisallow: /', '/about'), false);
  assert.equal(disallows('User-agent: *\nDisallow:', '/anything'), false, 'an empty Disallow permits everything');
});

test('a page with no logo gets a wordmark and a line saying so, never a logo from somewhere else', async () => {
  const fetchPage = async () => ({
    html: '<title>Acme | Gyms</title><meta property="og:description" content="Book a class.">',
    css: ':root{--brand:#0B5}',
    base: 'https://acme.test/',
  });
  const result = await extractBrand('https://acme.test/', { fetchPage, now: () => new Date('2026-01-02') });

  assert.equal(result.logo, null);
  assert.ok(result.missing.some((note) => /no logo found/.test(note)));
  assert.equal(result.notice, null, 'there is no third-party mark to warn about');
  assert.equal(result.source, 'acme.test', 'provenance is recorded, so nobody wonders where the colour came from');
  assert.equal(result.brand.company.name, 'Acme');
  assert.equal(result.brand.company.tagline, 'Book a class.');
  assert.equal(result.fetchedAt, '2026-01-02');
  assert.match(wordmarkSvg(result.brand.company.name, result.brand), /Acme/);
});

test('when a logo is found, whose it is gets recorded rather than assumed', async () => {
  const fetchPage = async () => ({
    html: '<title>Acme</title><link rel="icon" href="/logo.svg">',
    css: '',
    base: 'https://acme.test/',
  });
  const result = await extractBrand('https://acme.test/', { fetchPage });
  assert.equal(result.logo.url, 'https://acme.test/logo.svg');
  assert.match(result.notice, /responsible for having permission/);
});

