// ------------------------------------------------------------ history and diffs (§7)

const model = (over = {}) => ({
  containers: [], externals: [], entities: [], components: [], requirements: [], ...over,
});

test('the diff says what changed architecturally, in the words a reviewer would use', () => {
  const before = model({ containers: [{ name: 'API' }], entities: [{ name: 'Member', class: 'internal', fields: [{ name: 'id' }] }] });
  const after = model({
    containers: [{ name: 'API' }, { name: 'Worker' }],
    externals: [{ name: 'Stripe' }],
    entities: [{ name: 'Member', class: 'personal', fields: [{ name: 'id' }, { name: 'email' }] }, { name: 'Refund', class: 'financial', fields: [] }],
    requirements: [{ id: 'R-001', title: 'take payments', status: 'done' }],
  });

  const { markdown, unchanged } = compareModels(before, after, { from: 'v0.1.0', to: 'v0.2.0' });
  assert.equal(unchanged, false);
  assert.match(markdown, /\*\*Worker\*\* added/);
  assert.match(markdown, /now calls \*\*Stripe\*\*/);
  assert.match(markdown, /\*\*Refund\*\* added/);
  assert.match(markdown, /Member gained email/);
  assert.match(markdown, /\*\*Member is now classified personal, was internal\*\*/, 'the classification change is the line a security reviewer is looking for');
  assert.match(markdown, /R-001 take payments/);
});

test('two points with the same architecture say so, instead of printing empty headings', () => {
  const same = model({ containers: [{ name: 'API' }] });
  const { markdown, unchanged } = compareModels(same, same, { from: 'a', to: 'b' });
  assert.equal(unchanged, true);
  assert.match(markdown, /Nothing changed architecturally/);
});

test('the past is rebuilt without touching what somebody is working on', async () => {
  const root = await project();
  gitInit(root);
  sh(root, 'git', 'tag', 'v0.1.0');
  await writeFile(join(root, 'work-in-progress.txt'), 'half finished');

  const seen = await atCommit(root, 'v0.1.0', async (tree) => {
    const { readdir } = await import('node:fs/promises');
    return readdir(tree);
  });

  assert.ok(seen.includes('vibekit'), 'the worktree is the repository as it was');
  assert.ok(!seen.includes('work-in-progress.txt'), 'the tag predates it');
  assert.equal(await readFile(join(root, 'work-in-progress.txt'), 'utf8'), 'half finished', 'the working tree was left alone');
  assert.match(commitDate(root, 'v0.1.0'), /^\d{4}-\d{2}-\d{2}$/);
});

