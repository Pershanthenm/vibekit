test('the real fetch reads one page and its stylesheet, and stops at robots.txt', async () => {
  const { createServer } = await import('node:http');
  const pages = {
    '/robots.txt': 'User-agent: *\nDisallow: /private\n',
    '/': '<title>Acme | Gyms</title><link rel="stylesheet" href="/site.css"><link rel="icon" href="/logo.svg">',
    '/site.css': ':root { --brand: #2266aa; } body { font-family: "Inter", sans-serif }',
  };
  const asked = [];
  const server = createServer((request, response) => {
    asked.push(request.url);
    const body = pages[request.url];
    response.writeHead(body === undefined ? 404 : 200, { 'content-type': 'text/plain' });
    response.end(body ?? 'no');
  });
  await new Promise((ready) => server.listen(0, '127.0.0.1', ready));
  const base = `http://127.0.0.1:${server.address().port}`;

  try {
    // No injected fetcher: this is the path that actually runs when somebody passes a URL. The
    // server is on loopback, which the guard refuses by default — so the refusal is asserted first
    // and the flag that says "internal is the point" is what lets the rest of the test run.
    await assert.rejects(() => extractBrand(`${base}/`), /loopback.*--allow-private/);
    const result = await extractBrand(`${base}/`, { allowPrivate: true });
    assert.equal(result.brand.colour.brand, '#2266AA');
    assert.match(result.brand.type.heading, /Inter/);
    assert.equal(result.logo.url, `${base}/logo.svg`);
    assert.ok(asked.includes('/robots.txt'), 'robots.txt is read before the page, not after');
    assert.ok(asked.includes('/site.css'), 'the stylesheet is where the colours are');

    await assert.rejects(() => extractBrand(`${base}/private/deck`, { allowPrivate: true }), /robots\.txt disallows \/private/);
  } finally {
    await new Promise((closed) => server.close(closed));
  }
});



