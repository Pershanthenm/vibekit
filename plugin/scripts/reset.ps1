# Removes every trace of Vibe-check-cli from this machine, then installs it fresh from this copy.
# Leaves Claude Code, your Claude sign-in, Cursor, your other plugins and your projects alone.
#
# Usage (from Claude or PowerShell):
#   Expand-Archive "$HOME\Downloads\vibe-check-cli.zip" -DestinationPath "$env:TEMP\vibecheck-fresh" -Force
#   & "$env:TEMP\vibecheck-fresh\vibe-check-cli\plugin\scripts\reset.ps1"
$ErrorActionPreference = 'Continue'
$source = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path.TrimEnd('\', '/')
$target = [IO.Path]::Combine($HOME, 'tools', 'vibe-check-cli')
$pluginsDir = [IO.Path]::Combine($HOME, '.claude', 'plugins')

function Write-Step($message) { Write-Host ''; Write-Host "== $message" }

Write-Step 'Removing the old Vibe-check-cli plugin from Claude Code'
if (Get-Command claude -ErrorAction SilentlyContinue) {
  & claude plugin uninstall vibe-check-cli@vibe-check-cli 2>&1 | Out-Host
  & claude plugin marketplace remove vibe-check-cli 2>&1 | Out-Host
}
foreach ($leftover in @([IO.Path]::Combine($pluginsDir, 'cache', 'vibe-check-cli'), [IO.Path]::Combine($pluginsDir, 'marketplaces', 'vibe-check-cli'))) {
  if (Test-Path $leftover) { Remove-Item -Recurse -Force $leftover -ErrorAction SilentlyContinue; Write-Host "removed $leftover" }
}

Write-Step 'Removing Vibe-check-cli subagents from Cursor'
$cursorAgentsDir = [IO.Path]::Combine($HOME, '.cursor', 'agents')
$cursorTeamSkills = [IO.Path]::Combine($HOME, '.cursor', 'skills', 'vibe-check-cli')
if (Test-Path $cursorTeamSkills) { Remove-Item -Recurse -Force $cursorTeamSkills; Write-Host "removed $cursorTeamSkills" }
if (Test-Path $cursorAgentsDir) {
  Get-ChildItem -Path $cursorAgentsDir -Filter '*.md' | Where-Object { (Get-Content -Raw -Path $_.FullName) -match 'Generated by Vibe-check-cli' } | ForEach-Object { Remove-Item -Force $_.FullName; Write-Host "removed $($_.FullName)" }
}

Write-Step 'Removing the old vibecheck command'
if (Get-Command npm -ErrorAction SilentlyContinue) { & npm uninstall -g vibe-check-cli 2>&1 | Out-Host }

Write-Step 'Removing old files and saved preferences'
$sameFolder = (Test-Path $target) -and ((Resolve-Path $target).Path.TrimEnd('\', '/') -eq $source)
if (-not $sameFolder) {
  if (Test-Path $target) { Remove-Item -Recurse -Force $target; Write-Host "removed $target" }
  New-Item -ItemType Directory -Force -Path (Split-Path $target) | Out-Null
  Copy-Item -Recurse -Force -Path $source -Destination $target
  Write-Host "copied the fresh version to $target"
}
foreach ($saved in @('preferences.json', 'components.json')) {
  $file = [IO.Path]::Combine($HOME, '.vibe-check-cli', $saved)
  if (Test-Path $file) { Remove-Item -Force $file; Write-Host "removed $file" }
}
Write-Host 'kept your list of projects (~/.vibe-check-cli/projects.json)'

Write-Step 'Installing fresh'
& ([IO.Path]::Combine($target, 'plugin', 'scripts', 'bootstrap.ps1')) --minimal --yes

Write-Step 'What Claude Code now has'
if (Get-Command claude -ErrorAction SilentlyContinue) { & claude plugin details vibe-check-cli@vibe-check-cli 2>&1 | Select-Object -First 12 | Out-Host }
Write-Host ''
Write-Host 'Done. In Claude Code: type /reload-plugins (or fully restart Cursor), then run /vibe-check-cli:setup'
