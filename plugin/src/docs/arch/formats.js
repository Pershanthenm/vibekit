import { execFileSync } from 'node:child_process';
import { readFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { which } from '../../which.js';

/**
 * Output formats. Documentation Feature Spec §4 (Output formats).
 *
 * **HTML is produced here**: a single self-contained file with the diagrams inlined as SVG, so it
 * renders offline and in five years with nothing installed. That is the format the spec describes
 * most precisely and the one a reader is most likely to open.
 *
 * **Word and PDF are converted, not written here, and the reason is worth stating plainly.** The
 * spec asks for PNG in those formats. Turning our SVG into PNG means rasterising vector text,
 * which needs a font engine; there is no honest way to hand-roll one, and writing a PDF that
 * embeds no diagrams would be worse than saying so. `pandoc`, `libreoffice` or `wkhtmltopdf`
 * already do this well, so VibeKit detects one and drives it, and names what to install when
 * there is none. A missing converter is reported, never silently downgraded to a worse document.
 */

export const FORMATS = Object.freeze(['md', 'html', 'docx', 'pdf']);

const CONVERTERS = {
  docx: [
    { command: 'pandoc', args: (input, output) => [input, '-o', output, '--resource-path', dirname(input)] },
    { command: 'libreoffice', args: (input, output) => ['--headless', '--convert-to', 'docx', '--outdir', dirname(output), input] },
  ],
  pdf: [
    { command: 'pandoc', args: (input, output) => [input, '-o', output, '--resource-path', dirname(input)] },
    { command: 'wkhtmltopdf', args: (input, output) => [input, output] },
    { command: 'libreoffice', args: (input, output) => ['--headless', '--convert-to', 'pdf', '--outdir', dirname(output), input] },
  ],
};

export const converterFor = (format) => (CONVERTERS[format] ?? []).find((candidate) => which(candidate.command)) ?? null;

const escape = (text) => String(text ?? '').replace(/[&<>]/g, (char) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' }[char]));

/**
 * Markdown to a single self-contained HTML file.
 *
 * Deliberately a small renderer rather than a dependency: the documents are generated by us, so
 * the Markdown they contain is a known subset — headings, paragraphs, tables, lists, images,
 * code fences, bold and inline code. Anything outside that is passed through escaped rather than
 * half-rendered.
 */
export function markdownToHtml(markdown, { images = new Map() } = {}) {
  const lines = String(markdown).replace(/\r\n/g, '\n').split('\n');
  const out = [];
  let index = 0;

  const inline = (text) => escape(text)
    .replace(/`([^`]+)`/g, (whole, code) => `<code>${code}</code>`)
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/(?<!\*)\*([^*\n]+)\*(?!\*)/g, '<em>$1</em>')
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2">$1</a>');

  while (index < lines.length) {
    const line = lines[index];

    if (/^<!--/.test(line)) { index += 1; continue; }

    if (!line.trim()) { index += 1; continue; }

    const image = line.match(/^!\[([^\]]*)\]\(([^)]+)\)\s*$/);
    if (image) {
      const inlined = images.get(image[2]);
      out.push(inlined
        ? `<figure>${inlined}<figcaption>${escape(image[1])}</figcaption></figure>`
        : `<figure><img src="${escape(image[2])}" alt="${escape(image[1])}"><figcaption>${escape(image[1])}</figcaption></figure>`);
      index += 1;
      continue;
    }

    const heading = line.match(/^(#{1,6})\s+(.*)$/);
    if (heading) {
      out.push(`<h${heading[1].length}>${inline(heading[2])}</h${heading[1].length}>`);
      index += 1;
      continue;
    }

    if (line.startsWith('```')) {
      const body = [];
      index += 1;
      while (index < lines.length && !lines[index].startsWith('```')) { body.push(lines[index]); index += 1; }
      index += 1;
      out.push(`<pre><code>${escape(body.join('\n'))}</code></pre>`);
      continue;
    }

    if (line.startsWith('|')) {
      const rows = [];
      while (index < lines.length && lines[index].startsWith('|')) { rows.push(lines[index]); index += 1; }
      const cells = (row) => row.split('|').slice(1, -1).map((cell) => cell.trim());
      const [head, , ...body] = rows;
      out.push([
        '<table>',
        `<thead><tr>${cells(head).map((cell) => `<th>${inline(cell)}</th>`).join('')}</tr></thead>`,
        `<tbody>${body.map((row) => `<tr>${cells(row).map((cell) => `<td>${inline(cell)}</td>`).join('')}</tr>`).join('')}</tbody>`,
        '</table>',
      ].join('\n'));
      continue;
    }

    if (/^[-*]\s+/.test(line)) {
      const items = [];
      while (index < lines.length && /^[-*]\s+/.test(lines[index])) { items.push(lines[index].replace(/^[-*]\s+/, '')); index += 1; }
      out.push(`<ul>${items.map((item) => `<li>${inline(item)}</li>`).join('')}</ul>`);
      continue;
    }

    if (/^\d+[.)]\s+/.test(line)) {
      const items = [];
      while (index < lines.length && /^\d+[.)]\s+/.test(lines[index])) { items.push(lines[index].replace(/^\d+[.)]\s+/, '')); index += 1; }
      out.push(`<ol>${items.map((item) => `<li>${inline(item)}</li>`).join('')}</ol>`);
      continue;
    }

    const paragraph = [];
    while (index < lines.length && lines[index].trim() && !/^[|#`]|^[-*]\s|^\d+[.)]\s|^!\[/.test(lines[index])) {
      paragraph.push(lines[index]);
      index += 1;
    }
    if (paragraph.length) out.push(`<p>${inline(paragraph.join(' '))}</p>`);
    else index += 1;
  }

  return out.join('\n');
}

/** Every diagram a document references, read from disk so the HTML carries them inside it. */
export async function inlineImages(markdown, docsRoot) {
  const images = new Map();
  for (const match of String(markdown).matchAll(/!\[[^\]]*\]\(([^)]+)\)/g)) {
    const reference = match[1];
    if (/^https?:/i.test(reference)) continue;
    const svg = await readFile(join(docsRoot, reference), 'utf8').catch(() => null);
    if (svg && svg.trimStart().startsWith('<svg')) images.set(reference, svg.replace(/<\?xml[^>]*\?>/, '').trim());
  }
  return images;
}

export async function toHtml(markdown, { docsRoot, brand, title }) {
  const images = await inlineImages(markdown, docsRoot);
  const body = markdownToHtml(markdown, { images });
  const colour = brand?.colour ?? {};
  const type = brand?.type ?? {};

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escape(title)}</title>
<style>
  :root { --brand: ${colour.brand ?? '#1F5673'}; --ink: ${colour.diagram_text ?? colour.text ?? '#14171C'}; --line: #D9DEE4; }
  body { max-width: 62rem; margin: 0 auto; padding: 2.5rem 1.25rem 5rem; color: var(--ink);
         font-family: ${escape(type.body ?? 'system-ui, sans-serif')}; line-height: 1.6; }
  h1, h2, h3 { font-family: ${escape(type.heading ?? 'system-ui, sans-serif')}; line-height: 1.25; }
  h1 { color: var(--brand); border-bottom: 3px solid var(--brand); padding-bottom: .4rem; }
  h2 { margin-top: 2.5rem; }
  table { border-collapse: collapse; width: 100%; margin: 1rem 0; font-size: .94rem; }
  th, td { border: 1px solid var(--line); padding: .5rem .65rem; text-align: left; vertical-align: top; }
  th { background: color-mix(in srgb, var(--brand) 10%, #fff); }
  figure { margin: 1.5rem 0; }
  figure svg { max-width: 100%; height: auto; }
  figcaption { font-size: .82rem; color: #667; margin-top: .4rem; }
  code { background: #F3F5F7; padding: .1rem .3rem; border-radius: 3px; font-family: ${escape(type.mono ?? 'ui-monospace, monospace')}; }
  pre { background: #F3F5F7; padding: .9rem; border-radius: 6px; overflow-x: auto; }
  @media print { body { max-width: none; } h2 { break-before: auto; } figure, table { break-inside: avoid; } }
</style>
</head>
<body>
${body}
</body>
</html>
`;
}

/**
 * Convert a written file. Returns what happened rather than throwing, so one missing converter
 * does not cost the caller the formats that did work.
 */
export function convert(inputPath, outputPath, format) {
  const converter = converterFor(format);
  if (!converter) {
    return {
      ok: false,
      format,
      reason: `no converter for ${format}. Install pandoc (recommended) or ${format === 'pdf' ? 'wkhtmltopdf' : 'libreoffice'}, then run this again. Nothing was written — a ${format} without its diagrams would be worse than none.`,
    };
  }
  try {
    execFileSync(converter.command, converter.args(inputPath, outputPath), { stdio: ['ignore', 'ignore', 'pipe'] });
    return { ok: true, format, by: converter.command, path: outputPath };
  } catch (error) {
    return { ok: false, format, reason: `${converter.command} failed: ${String(error.stderr ?? error.message).trim().split('\n')[0]}` };
  }
}
